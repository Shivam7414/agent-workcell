-- Reference ERP: purchase-to-pay for a made-up buying company.
-- The demo, the tests and the benchmarks all run on this schema. Every row is made up by seed.py.
--
-- Some things here are awkward on purpose, because real systems are. See reference_erp/README.md ("Traps").
-- Run once on an empty database. seed.py does this for you.

CREATE TYPE user_role AS ENUM ('admin', 'buyer', 'supplier_user');
CREATE TYPE supplier_status AS ENUM ('active', 'on_hold', 'blocked');
CREATE TYPE po_status AS ENUM ('draft', 'pending_approval', 'approved', 'sent', 'partially_received', 'received',
    'closed', 'cancelled');
CREATE TYPE receipt_status AS ENUM ('posted', 'reversed');
CREATE TYPE invoice_status AS ENUM ('submitted', 'under_review', 'approved', 'rejected', 'payment_scheduled', 'paid');
CREATE TYPE payment_method AS ENUM ('ach', 'wire', 'check');
CREATE TYPE payment_status AS ENUM ('scheduled', 'sent', 'cleared', 'failed');

CREATE TABLE departments (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          text NOT NULL UNIQUE,
    name          text NOT NULL,
    annual_budget numeric(14, 2) NOT NULL
);

CREATE TABLE products (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku        text NOT NULL UNIQUE,
    name       text NOT NULL,
    category   text NOT NULL,
    unit       text NOT NULL,
    list_price numeric(14, 2) NOT NULL,
    is_active  boolean NOT NULL DEFAULT true,
    deleted_at timestamptz
);

CREATE TABLE suppliers (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_number    text NOT NULL UNIQUE,          -- the number people use, not the id
    name               text NOT NULL,
    status             supplier_status NOT NULL DEFAULT 'active',
    city               text,
    payment_terms_days integer NOT NULL DEFAULT 30,
    tax_id             text,                          -- sensitive
    bank_account       text,                          -- sensitive
    created_at         timestamptz NOT NULL DEFAULT now(),
    deleted_at         timestamptz
);

CREATE TABLE users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         text NOT NULL UNIQUE,
    password_hash text NOT NULL,                      -- never readable by the assistant
    full_name     text NOT NULL,
    role          user_role NOT NULL,
    supplier_id   bigint REFERENCES suppliers (id),   -- set only for supplier users
    is_active     boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now(),
    deleted_at    timestamptz,
    CHECK ((role = 'supplier_user') = (supplier_id IS NOT NULL))
);

CREATE TABLE purchase_orders (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number     text NOT NULL UNIQUE,               -- the number people use, not the id
    supplier_id   bigint NOT NULL REFERENCES suppliers (id),
    buyer_id      bigint NOT NULL REFERENCES users (id),
    department_id bigint NOT NULL REFERENCES departments (id),
    status        po_status NOT NULL DEFAULT 'draft',
    order_date    date NOT NULL,
    expected_date date,
    approved_by   bigint,                             -- a user id, with no foreign key
    approved_at   timestamptz,
    notes         text,                               -- free text typed by people
    created_at    timestamptz NOT NULL DEFAULT now(),
    deleted_at    timestamptz
);

-- There is no stored line total and no stored order total. See the README for the formula.
CREATE TABLE purchase_order_lines (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL REFERENCES purchase_orders (id),
    line_no           integer NOT NULL,
    product_id        bigint NOT NULL REFERENCES products (id),
    description       text NOT NULL,
    quantity          numeric(12, 2) NOT NULL,
    unit_price        numeric(14, 2) NOT NULL,
    discount_pct      numeric(5, 2),                  -- empty means no discount
    tax_rate          numeric(5, 2),                  -- empty means no tax
    UNIQUE (purchase_order_id, line_no)
);

CREATE TABLE goods_receipts (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number    text NOT NULL UNIQUE,
    purchase_order_id bigint NOT NULL REFERENCES purchase_orders (id),
    received_by       bigint,                         -- a user id, with no foreign key
    received_date     date NOT NULL,
    status            receipt_status NOT NULL DEFAULT 'posted',
    note              text,
    created_at        timestamptz NOT NULL DEFAULT now()
);

-- quantity_received is everything that arrived. quantity_rejected is the part sent back.
CREATE TABLE goods_receipt_lines (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goods_receipt_id       bigint NOT NULL REFERENCES goods_receipts (id),
    purchase_order_line_id bigint NOT NULL REFERENCES purchase_order_lines (id),
    quantity_received      numeric(12, 2) NOT NULL,
    quantity_rejected      numeric(12, 2) NOT NULL DEFAULT 0
);

-- Invoices are never soft-deleted. invoice_number is the supplier's own number, so two suppliers can use the same one.
CREATE TABLE supplier_invoices (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_number   text NOT NULL UNIQUE,           -- our number for the invoice
    invoice_number    text NOT NULL,                  -- the supplier's number
    supplier_id       bigint NOT NULL REFERENCES suppliers (id),
    purchase_order_id bigint,                         -- empty for invoices with no order. No foreign key
    status            invoice_status NOT NULL DEFAULT 'submitted',
    invoice_date      date NOT NULL,
    due_date          date NOT NULL,
    subtotal          numeric(14, 2) NOT NULL,
    tax_amount        numeric(14, 2) NOT NULL DEFAULT 0,
    total_amount      numeric(14, 2) NOT NULL,
    rejection_reason  text,
    submitted_by      bigint,                         -- a user id, with no foreign key
    reviewed_by       bigint,                         -- a user id, with no foreign key
    reviewed_at       timestamptz,
    created_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (supplier_id, invoice_number)
);

CREATE TABLE supplier_invoice_lines (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_invoice_id    bigint NOT NULL REFERENCES supplier_invoices (id),
    purchase_order_line_id bigint,                    -- empty for invoices with no order. No foreign key
    description            text NOT NULL,
    quantity               numeric(12, 2) NOT NULL,
    unit_price             numeric(14, 2) NOT NULL,
    amount                 numeric(14, 2) NOT NULL
);

-- A payment has no order and no invoice column. It reaches invoices only through payment_allocations.
CREATE TABLE payments (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_number text NOT NULL UNIQUE,
    supplier_id    bigint NOT NULL REFERENCES suppliers (id),
    method         payment_method NOT NULL,
    status         payment_status NOT NULL DEFAULT 'scheduled',
    payment_date   date NOT NULL,
    amount         numeric(14, 2) NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE payment_allocations (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id          bigint NOT NULL REFERENCES payments (id),
    supplier_invoice_id bigint NOT NULL REFERENCES supplier_invoices (id),
    amount              numeric(14, 2) NOT NULL
);

-- Internal log. entity_id points to a different table depending on entity_type.
CREATE TABLE audit_log (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint,
    action      text NOT NULL,
    entity_type text NOT NULL,
    entity_id   bigint NOT NULL,
    detail      text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON users (supplier_id);
CREATE INDEX ON purchase_orders (supplier_id);
CREATE INDEX ON purchase_orders (buyer_id);
CREATE INDEX ON purchase_orders (department_id);
CREATE INDEX ON purchase_orders (order_date);
CREATE INDEX ON purchase_order_lines (product_id);
CREATE INDEX ON goods_receipts (purchase_order_id);
CREATE INDEX ON goods_receipt_lines (goods_receipt_id);
CREATE INDEX ON goods_receipt_lines (purchase_order_line_id);
CREATE INDEX ON supplier_invoices (purchase_order_id);
CREATE INDEX ON supplier_invoices (status);
CREATE INDEX ON supplier_invoice_lines (supplier_invoice_id);
CREATE INDEX ON supplier_invoice_lines (purchase_order_line_id);
CREATE INDEX ON payments (supplier_id);
CREATE INDEX ON payment_allocations (payment_id);
CREATE INDEX ON payment_allocations (supplier_invoice_id);
CREATE INDEX ON audit_log (entity_type, entity_id);
