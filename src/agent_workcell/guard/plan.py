"""Turn a policy into the SQL that installs the guard.

The output is meant to be read by a database administrator before it runs. It creates:

- three roles: the guard role (owns the views, cannot log in), the agent role (reads the views and nothing else), and
  the binder role (can only record who is using an agent connection);
- the schema `guard`, with one security_barrier view per table in the policy;
- the schema `guard_internal`, with the table that records who is asking, and the functions that write it.

Names come from the validated policy and are quoted with the driver's identifier quoting. Row rules are trusted policy
SQL and are inserted as written.
"""

from __future__ import annotations

from dataclasses import dataclass

from psycopg import sql

from agent_workcell.policy import NAME, Policy


@dataclass(frozen=True)
class Names:
    """Names of the database objects the guard creates."""

    guard_role: str = "workcell_guard"
    agent_role: str = "workcell_agent"
    binder_role: str = "workcell_binder"
    views: str = "guard"
    internal: str = "guard_internal"

    def __post_init__(self) -> None:
        for value in vars(self).values():
            if not NAME.match(value):
                raise ValueError(f"{value!r} is not a valid database name")


DEFAULT_NAMES = Names()


def installed_marker(policy: Policy) -> str:
    """The comment on the views schema that records which policy is installed."""
    return f"agent-workcell policy sha256:{policy.digest}"


def bind_call(policy: Policy, names: Names = DEFAULT_NAMES) -> sql.Composed:
    """SELECT guard_internal.bind(pid, backend_start, role, attributes...), with one placeholder per value."""
    types = ["integer", "timestamptz", "text", *policy.attributes.values()]
    return sql.SQL("SELECT {}.bind({})").format(
        sql.Identifier(names.internal),
        sql.SQL(", ").join(sql.SQL("{}::{}").format(sql.Placeholder(), sql.SQL(kind)) for kind in types),
    )


def install(conn, policy: Policy, agent_password: str, binder_password: str, names: Names = DEFAULT_NAMES) -> None:
    """Run the plan and set the login passwords. For development and tests; in production an administrator reviews
    the plan and runs it."""
    if not agent_password or not binder_password:
        raise ValueError("Both passwords are required.")
    conn.autocommit = True
    conn.execute(plan_sql(policy, names))
    for role, password in ((names.agent_role, agent_password), (names.binder_role, binder_password)):
        conn.execute(sql.SQL("ALTER ROLE {} PASSWORD {}").format(sql.Identifier(role), sql.Literal(password)))


def plan_sql(policy: Policy, names: Names = DEFAULT_NAMES) -> str:
    return sql.SQL("\n").join([
        _header(policy, names),
        _roles(names),
        _guard_role_grants(policy, names),
        _schemas(names),
        sql.SQL("SET LOCAL ROLE {};\nSET LOCAL search_path = {};\n").format(
            sql.Identifier(names.guard_role), sql.Identifier(policy.schema)),
        _identity(policy, names),
        *(_view(policy, table, names) for table in policy.tables),
        sql.SQL("RESET ROLE;\n"),
        _grants(policy, names),
        sql.SQL("COMMIT;\n"),
    ]).as_string()


def _header(policy: Policy, names: Names) -> sql.Composed:
    return sql.SQL(
        "-- Agent Workcell data guard. Generated by \"guard plan\". Do not edit by hand.\n"
        "-- Policy sha256: {digest}\n"
        "--\n"
        "-- Review this file, then run it once as a superuser. It is safe to run again after the policy changes:\n"
        "-- agent connections bound at that moment lose their identity and see no rows until they are bound again.\n"
        "-- Afterwards, give the two login roles a password:\n"
        "--   ALTER ROLE {agent} PASSWORD '...';\n"
        "--   ALTER ROLE {binder} PASSWORD '...';\n"
        "\n"
        "BEGIN;\n"
    ).format(digest=sql.SQL(policy.digest), agent=sql.Identifier(names.agent_role),
             binder=sql.Identifier(names.binder_role))


def _roles(names: Names) -> sql.Composed:
    create = sql.SQL(
        "    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = {literal}) THEN\n"
        "        CREATE ROLE {role};\n"
        "    END IF;\n"
    )
    limits = sql.SQL("ALTER ROLE {} {} NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;\n")
    roles = [(names.guard_role, "NOLOGIN"), (names.agent_role, "LOGIN"), (names.binder_role, "LOGIN")]
    return sql.Composed([
        sql.SQL("-- 1. Roles, created when missing. None of them can create roles or databases, or bypass row "
                "security.\nDO $$\nBEGIN\n"),
        *(create.format(literal=sql.Literal(role), role=sql.Identifier(role)) for role, _ in roles),
        sql.SQL("END\n$$;\n"),
        *(limits.format(sql.Identifier(role), sql.SQL(login)) for role, login in roles),
    ])


def _guard_role_grants(policy: Policy, names: Names) -> sql.Composed:
    return sql.SQL(
        "\n-- 2. The guard role reads the tables in the policy, and no other table in that schema.\n"
        "REVOKE ALL ON ALL TABLES IN SCHEMA {schema} FROM {guard};\n"
        "GRANT USAGE ON SCHEMA {schema} TO {guard};\n"
        "GRANT SELECT ON TABLE {tables} TO {guard};\n"
    ).format(
        schema=sql.Identifier(policy.schema),
        guard=sql.Identifier(names.guard_role),
        tables=sql.SQL(", ").join(sql.Identifier(policy.schema, table) for table in policy.tables),
    )


def _schemas(names: Names) -> sql.Composed:
    return sql.SQL(
        "\n-- 3. {views} holds the views the agent reads. {internal} records who is asking; the agent cannot see it.\n"
        "DROP SCHEMA IF EXISTS {views} CASCADE;\n"
        "DROP SCHEMA IF EXISTS {internal} CASCADE;\n"
        "CREATE SCHEMA {internal} AUTHORIZATION {guard};\n"
        "CREATE SCHEMA {views} AUTHORIZATION {guard};\n"
        "REVOKE ALL ON SCHEMA {internal}, {views} FROM PUBLIC;\n"
    ).format(views=sql.Identifier(names.views), internal=sql.Identifier(names.internal),
             guard=sql.Identifier(names.guard_role))


def _identity(policy: Policy, names: Names) -> sql.Composed:
    internal = sql.Identifier(names.internal)
    attributes = list(policy.attributes.items())
    columns = sql.SQL("").join(
        sql.SQL("    {} {}{},\n").format(sql.Identifier(f"principal_{name}"), sql.SQL(kind),
                                         sql.SQL(" NOT NULL" if name == "user_id" else ""))
        for name, kind in attributes
    )
    principal_columns = sql.SQL(", ").join(
        sql.SQL("s.{}").format(sql.Identifier(f"principal_{name}")) for name, _ in attributes)
    parameters = sql.SQL(", ").join(
        sql.SQL("{} {}").format(sql.Identifier(f"p_{name}"), sql.SQL(kind)) for name, kind in attributes)
    parameter_types = sql.SQL(", ").join(sql.SQL(kind) for _, kind in attributes)
    insert_columns = sql.SQL(", ").join(sql.Identifier(f"principal_{name}") for name, _ in attributes)
    insert_values = sql.SQL(", ").join(sql.Identifier(f"p_{name}") for name, _ in attributes)

    return sql.SQL(
        "\n-- 4. Who is asking: one row per bound agent connection. backend_start tells apart two connections that\n"
        "-- got the same process id one after the other.\n"
        "CREATE TABLE {internal}.sessions (\n"
        "    pid integer PRIMARY KEY,\n"
        "    backend_start timestamptz NOT NULL,\n"
        "    principal_role text NOT NULL,\n"
        "{columns}"
        "    bound_at timestamptz NOT NULL DEFAULT now()\n"
        ");\n"
        "\n"
        "-- The person bound to the current connection, or no row at all.\n"
        "CREATE VIEW {internal}.principal AS\n"
        "SELECT s.principal_role, {principal_columns}\n"
        "FROM {internal}.sessions AS s\n"
        "WHERE s.pid = pg_catalog.pg_backend_pid()\n"
        "  AND s.backend_start = (SELECT a.backend_start\n"
        "                         FROM pg_catalog.pg_stat_get_activity(pg_catalog.pg_backend_pid()) AS a);\n"
        "\n"
        "-- Called by trusted server code, through the binder role, before the agent's first query.\n"
        "CREATE FUNCTION {internal}.bind(p_pid integer, p_backend_start timestamptz, p_role text, {parameters})\n"
        "RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$\n"
        "BEGIN\n"
        "    IF p_role IS NULL OR p_role <> ALL (ARRAY[{roles}]::text[]) THEN\n"
        "        RAISE EXCEPTION 'guard: role % is not in the policy', p_role;\n"
        "    END IF;\n"
        "    IF p_user_id IS NULL THEN\n"
        "        RAISE EXCEPTION 'guard: user_id is required';\n"
        "    END IF;\n"
        "    IF NOT EXISTS (SELECT FROM pg_stat_activity AS a\n"
        "                   WHERE a.pid = p_pid AND a.usename = {agent} AND a.datname = current_database()) THEN\n"
        "        RAISE EXCEPTION 'guard: process % is not an agent connection to this database', p_pid;\n"
        "    END IF;\n"
        "    -- Forget connections that have ended, and an earlier connection that had the same process id.\n"
        "    DELETE FROM {internal}.sessions AS s\n"
        "    WHERE NOT EXISTS (SELECT FROM pg_stat_activity AS a WHERE a.pid = s.pid)\n"
        "       OR (s.pid = p_pid AND s.backend_start <> p_backend_start);\n"
        "    -- One connection serves one person.\n"
        "    IF EXISTS (SELECT FROM {internal}.sessions AS s WHERE s.pid = p_pid) THEN\n"
        "        RAISE EXCEPTION 'guard: process % is already bound to a person', p_pid;\n"
        "    END IF;\n"
        "    INSERT INTO {internal}.sessions (pid, backend_start, principal_role, {insert_columns})\n"
        "    VALUES (p_pid, p_backend_start, p_role, {insert_values});\n"
        "END\n"
        "$$;\n"
        "\n"
        "CREATE FUNCTION {internal}.unbind(p_pid integer, p_backend_start timestamptz)\n"
        "RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$\n"
        "    DELETE FROM {internal}.sessions WHERE pid = p_pid AND backend_start = p_backend_start;\n"
        "$$;\n"
        "\n"
        "REVOKE ALL ON FUNCTION {internal}.bind(integer, timestamptz, text, {parameter_types}) FROM PUBLIC;\n"
        "REVOKE ALL ON FUNCTION {internal}.unbind(integer, timestamptz) FROM PUBLIC;\n"
    ).format(
        internal=internal,
        columns=columns,
        principal_columns=principal_columns,
        parameters=parameters,
        parameter_types=parameter_types,
        roles=sql.SQL(", ").join(sql.Literal(role) for role in policy.roles),
        agent=sql.Literal(names.agent_role),
        insert_columns=insert_columns,
        insert_values=insert_values,
    )


def _principal_value(column: str, names: Names) -> sql.Composed:
    """An uncorrelated scalar subquery. PostgreSQL runs it once per query, and it is empty when nobody is bound."""
    return sql.SQL("(SELECT {} FROM {}.principal)").format(sql.Identifier(column), sql.Identifier(names.internal))


def _view(policy: Policy, name: str, names: Names) -> sql.Composed:
    """One view per table. CASE picks the rule for the bound person's role. No role, or no rule: no rows."""
    table = policy.tables[name]
    placeholders = {attribute: _principal_value(f"principal_{attribute}", names) for attribute in policy.attributes}
    branches = sql.SQL("").join(
        sql.SQL("    WHEN {role} THEN ({rule})\n").format(
            role=sql.Literal(role),
            rule=sql.SQL(rule).format(**placeholders),
        )
        for role, rule in table.rows.items()
    )
    return sql.SQL(
        "\n-- {name}: {visible} visible columns, {hidden} hidden. Rows for: {roles}.\n"
        "CREATE VIEW {view} WITH (security_barrier) AS\n"
        "SELECT {columns}\n"
        "FROM {table} AS t\n"
        "WHERE CASE {role}\n"
        "{conditions}"
        "    ELSE false\n"
        "END;\n"
    ).format(
        role=_principal_value("principal_role", names),
        name=sql.SQL(name),
        visible=sql.SQL(str(len(table.visible))),
        hidden=sql.SQL(str(len(table.hidden))),
        roles=sql.SQL(", ".join(table.rows)),
        view=sql.Identifier(names.views, name),
        columns=sql.SQL(", ").join(sql.SQL("t.{}").format(sql.Identifier(column)) for column in table.visible),
        table=sql.Identifier(policy.schema, name),
        conditions=branches,
    )


def _grants(policy: Policy, names: Names) -> sql.Composed:
    parameter_types = sql.SQL(", ").join(sql.SQL(kind) for kind in policy.attributes.values())
    return sql.SQL(
        "\n-- 5. The agent reads the guard views and nothing else. The binder can only bind and unbind.\n"
        "GRANT USAGE ON SCHEMA {views} TO {agent};\n"
        "GRANT SELECT ON TABLE {view_list} TO {agent};\n"
        "GRANT USAGE ON SCHEMA {internal} TO {binder};\n"
        "GRANT EXECUTE ON FUNCTION {internal}.bind(integer, timestamptz, text, {parameter_types}),\n"
        "                          {internal}.unbind(integer, timestamptz) TO {binder};\n"
        "COMMENT ON SCHEMA {views} IS {marker};\n"
        "\n"
    ).format(
        views=sql.Identifier(names.views),
        internal=sql.Identifier(names.internal),
        agent=sql.Identifier(names.agent_role),
        binder=sql.Identifier(names.binder_role),
        view_list=sql.SQL(", ").join(sql.Identifier(names.views, table) for table in policy.tables),
        parameter_types=parameter_types,
        marker=sql.Literal(installed_marker(policy)),
    )
