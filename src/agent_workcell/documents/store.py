"""The documents role, the job table, upload and the worker.

The upload and the worker write to the business database as their own role, the documents role. It may add versions,
set a version's status and error, add passages, and run its own job table. It cannot read any other table, change a
document, or read a passage back. `plan_sql` installs it; `check_role` proves at start-up that it can do no more.

A job is taken with FOR UPDATE SKIP LOCKED, so several workers never take the same one. A job whose worker stopped is
taken again once its lease has run out. A file that cannot be read fails at once with a message people can read. Any
other error is retried later, up to a limit.
"""

from __future__ import annotations

import os
import sys
import traceback
from dataclasses import dataclass
from itertools import islice
from pathlib import Path

import psycopg
from psycopg import sql

from agent_workcell.documents.chunk import chunks
from agent_workcell.documents.embed import BATCH_INPUTS, Embedder, embedding_input, vector_text
from agent_workcell.documents.read import ReadError, read_blocks
from agent_workcell.policy import NAME

MAX_ATTEMPTS = 3
RETRY_DELAY_S = 30.0  # doubled after each failed attempt
LEASE_S = 600.0  # a running job whose worker has not finished by then is taken again


@dataclass(frozen=True)
class DocumentNames:
    role: str = "workcell_documents"
    schema: str = "workcell_documents"  # holds the job table

    def __post_init__(self) -> None:
        for value in vars(self).values():
            if not NAME.match(value):
                raise ValueError(f"{value!r} is not a valid database name")


DEFAULT_DOCUMENT_NAMES = DocumentNames()


class UnknownDocument(LookupError):
    pass


# --------------------------------------------------------------------------------------------------------------------
# Install and check


def plan_sql(schema: str, names: DocumentNames = DEFAULT_DOCUMENT_NAMES) -> str:
    """SQL that creates the documents role and the job table, and gives the role exactly the rights it needs. Safe to
    run again: it keeps the jobs and sets the rights from nothing each time. `schema` holds the document tables."""
    return sql.SQL(
        "-- Agent Workcell documents. Generated by \"documents plan\". Do not edit by hand.\n"
        "-- Review this file, then run it once as the owner of the document tables. Afterwards, give the role a\n"
        "-- password: ALTER ROLE {role} PASSWORD '...';\n"
        "\nBEGIN;\n"
        "DO $$\nBEGIN\n"
        "    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = {role_literal}) THEN\n"
        "        CREATE ROLE {role};\n"
        "    END IF;\n"
        "END\n$$;\n"
        "ALTER ROLE {role} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;\n"
        "\nCREATE SCHEMA IF NOT EXISTS {jobs_schema};\n"
        "REVOKE ALL ON SCHEMA {jobs_schema} FROM PUBLIC;\n"
        "CREATE TABLE IF NOT EXISTS {jobs} (\n"
        "    id                  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,\n"
        "    document_version_id bigint NOT NULL UNIQUE REFERENCES {versions} (id) ON DELETE CASCADE,\n"
        "    status              text NOT NULL DEFAULT 'queued'\n"
        "                        CHECK (status IN ('queued', 'running', 'done', 'failed')),\n"
        "    attempts            integer NOT NULL DEFAULT 0,\n"
        "    run_after           timestamptz NOT NULL DEFAULT now(),\n"
        "    locked_until        timestamptz,\n"
        "    last_error          text,\n"
        "    created_at          timestamptz NOT NULL DEFAULT now(),\n"
        "    updated_at          timestamptz NOT NULL DEFAULT now()\n"
        ");\n"
        "CREATE INDEX IF NOT EXISTS jobs_due ON {jobs} (run_after) WHERE status IN ('queued', 'running');\n"
        "\n-- Rights, from nothing: add versions and set their status and error, add passages, run the jobs.\n"
        "REVOKE ALL ON ALL TABLES IN SCHEMA {schema} FROM {role};\n"
        "REVOKE ALL ON ALL TABLES IN SCHEMA {jobs_schema} FROM {role};\n"
        "GRANT USAGE ON SCHEMA {schema}, {jobs_schema} TO {role};\n"
        "GRANT SELECT, INSERT ON {versions} TO {role};\n"
        "GRANT UPDATE (status, error) ON {versions} TO {role};\n"
        "GRANT INSERT ON {chunks} TO {role};\n"
        "GRANT INSERT ON {embeddings} TO {role};\n"
        "GRANT SELECT, INSERT, UPDATE ON {jobs} TO {role};\n"
        "COMMIT;\n"
    ).format(
        role=sql.Identifier(names.role), role_literal=sql.Literal(names.role),
        schema=sql.Identifier(schema), jobs_schema=sql.Identifier(names.schema),
        jobs=sql.Identifier(names.schema, "jobs"), versions=sql.Identifier(schema, "document_versions"),
        chunks=sql.Identifier(schema, "document_chunks"),
        embeddings=sql.Identifier(schema, "document_chunk_embeddings"),
    ).as_string()


def install(conn, schema: str, password: str, names: DocumentNames = DEFAULT_DOCUMENT_NAMES) -> None:
    """Run the plan and set the password. For development and tests; in production an administrator runs the plan."""
    if not password:
        raise ValueError("A password is required.")
    conn.autocommit = True
    conn.execute(plan_sql(schema, names))
    conn.execute(sql.SQL("ALTER ROLE {} PASSWORD {}").format(sql.Identifier(names.role), sql.Literal(password)))


TABLE_RIGHTS = ("SELECT", "INSERT", "UPDATE", "DELETE", "TRUNCATE", "REFERENCES", "TRIGGER")
COLUMN_RIGHTS = ("SELECT", "INSERT", "UPDATE", "REFERENCES")


def check_role(conn, schema: str, names: DocumentNames = DEFAULT_DOCUMENT_NAMES) -> list[str]:
    """Run on a connection that logged in as the documents role. Returns every way the role can do more than its job,
    or is not the role at all. An empty list means the role checks out."""
    allowed = {
        (schema, "document_versions"): {"SELECT", "INSERT", "UPDATE"},  # UPDATE of two columns; checked below
        (schema, "document_chunks"): {"INSERT"},
        (schema, "document_chunk_embeddings"): {"INSERT"},
        (names.schema, "jobs"): {"SELECT", "INSERT", "UPDATE"},
    }
    problems = []
    user, flags = conn.execute(
        "SELECT current_user, ARRAY[rolsuper, rolcreatedb, rolcreaterole, rolreplication, rolbypassrls] "
        "FROM pg_catalog.pg_roles WHERE rolname = current_user").fetchone()
    if user != names.role:
        problems.append(f"the documents connection logs in as {user!r}, not as the documents role {names.role!r}")
    if any(flags):
        problems.append("the documents role has SUPERUSER, CREATEDB, CREATEROLE, REPLICATION or BYPASSRLS")
    if conn.execute("SELECT count(*) FROM pg_catalog.pg_auth_members m JOIN pg_catalog.pg_roles r ON r.oid = m.member "
                    "WHERE r.rolname = current_user").fetchone()[0]:
        problems.append("the documents role is a member of another role")
    if conn.execute("SELECT (SELECT count(*) FROM pg_catalog.pg_class WHERE relowner = r.oid) "
                    "+ (SELECT count(*) FROM pg_catalog.pg_namespace WHERE nspowner = r.oid) "
                    "FROM pg_catalog.pg_roles r WHERE r.rolname = current_user").fetchone()[0]:
        problems.append("the documents role owns tables or schemas")
    if conn.execute("SELECT has_database_privilege(current_database(), 'CREATE')").fetchone()[0]:
        problems.append("the documents role can create schemas in the database")
    for (nsp,) in conn.execute("SELECT nspname FROM pg_catalog.pg_namespace WHERE has_schema_privilege(oid, 'CREATE') "
                               "AND nspname NOT LIKE 'pg\\_%' AND nspname <> 'information_schema'"):
        problems.append(f"the documents role can create objects in schema {nsp}")

    # A right on some columns counts as a right on the table here; UPDATE on document_versions is checked per column.
    checks = sql.SQL(", ").join(
        sql.SQL("has_table_privilege(c.oid, {0}) OR has_any_column_privilege(c.oid, {0})" if right in COLUMN_RIGHTS
                else "has_table_privilege(c.oid, {0})").format(sql.Literal(right))
        for right in TABLE_RIGHTS)
    rows = conn.execute(sql.SQL(
        "SELECT n.nspname, c.relname, ARRAY[{checks}] FROM pg_catalog.pg_class c "
        "JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace "
        "WHERE c.relkind IN ('r', 'p', 'v', 'm', 'f') "
        "AND n.nspname NOT IN ('pg_catalog', 'information_schema') AND n.nspname NOT LIKE 'pg\\_toast%'"
    ).format(checks=checks)).fetchall()
    for nsp, table, granted in rows:
        rights = {right for right, has in zip(TABLE_RIGHTS, granted, strict=True) if has}
        extra = sorted(rights - allowed.get((nsp, table), set()))
        if extra:
            problems.append(f"the documents role has {', '.join(extra)} on {nsp}.{table}")
        if (nsp, table) in allowed and not allowed[(nsp, table)] <= rights:
            missing = sorted(allowed[(nsp, table)] - rights)
            problems.append(f"the documents role is missing {', '.join(missing)} on {nsp}.{table}")

    for nsp, sequence in conn.execute(
            "SELECT n.nspname, c.relname FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n "
            "ON n.oid = c.relnamespace WHERE c.relkind = 'S' AND (has_sequence_privilege(c.oid, 'USAGE') "
            "OR has_sequence_privilege(c.oid, 'SELECT') OR has_sequence_privilege(c.oid, 'UPDATE'))"):
        problems.append(f"the documents role has rights on sequence {nsp}.{sequence}")

    updatable = {column for (column,) in conn.execute(
        "SELECT attname FROM pg_catalog.pg_attribute WHERE attrelid = %s::regclass AND attnum > 0 "
        "AND NOT attisdropped AND has_column_privilege(attrelid, attnum, 'UPDATE')",
        [f"{schema}.document_versions"])}
    if updatable != {"status", "error"}:
        problems.append("the documents role must be able to update exactly status and error of document_versions, "
                        f"not {sorted(updatable)}")
    return problems


# --------------------------------------------------------------------------------------------------------------------
# Upload


@dataclass(frozen=True)
class Upload:
    document_id: int
    file_name: str
    media_type: str
    byte_size: int
    sha256: str
    uploaded_by: int


def register(conn, schema: str, storage_root: Path, upload: Upload, received: Path,
             names: DocumentNames = DEFAULT_DOCUMENT_NAMES) -> tuple[int, int]:
    """Add the next version of a document for a file already received, queue its job and move the file into place.
    Returns (version id, version number). The storage key is made of numbers and the file's hash, never its name."""
    versions = sql.Identifier(schema, "document_versions")
    try:
        with conn.transaction():
            # One upload per document at a time, so two uploads cannot take the same version number.
            conn.execute("SELECT pg_advisory_xact_lock(%s)", [upload.document_id])
            version_no = conn.execute(
                sql.SQL("SELECT COALESCE(MAX(version_no), 0) + 1 FROM {} WHERE document_id = %s").format(versions),
                [upload.document_id]).fetchone()[0]
            storage_key = f"{upload.document_id}/{version_no}/{upload.sha256}"
            version_id = conn.execute(sql.SQL(
                "INSERT INTO {} (document_id, version_no, file_name, media_type, byte_size, sha256, storage_key, "
                "status, uploaded_by) VALUES (%s, %s, %s, %s, %s, %s, %s, 'pending', %s) RETURNING id"
            ).format(versions), [upload.document_id, version_no, upload.file_name, upload.media_type,
                                 upload.byte_size, upload.sha256, storage_key, upload.uploaded_by]).fetchone()[0]
            conn.execute(sql.SQL("INSERT INTO {} (document_version_id) VALUES (%s)").format(
                sql.Identifier(names.schema, "jobs")), [version_id])
            target = stored_path(storage_root, storage_key)
            target.parent.mkdir(parents=True, exist_ok=True)
            os.replace(received, target)
    except psycopg.errors.ForeignKeyViolation:
        raise UnknownDocument(upload.document_id) from None
    return version_id, version_no


def stored_path(storage_root: Path, storage_key: str) -> Path:
    root = storage_root.resolve()
    path = (root / storage_key).resolve()
    if not path.is_relative_to(root):
        raise ValueError("a storage key points outside the document folder")
    return path


