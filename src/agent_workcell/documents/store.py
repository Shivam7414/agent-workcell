# The worker


@dataclass(frozen=True)
class Job:
    id: int
    version_id: int
    attempt: int  # 1 for the first try. A job belongs to the worker whose attempt it is.
    storage_key: str
    media_type: str


class _NotOurs(Exception):
    """Another worker took the job after this worker's lease ran out."""


def process_next(conn, schema: str, storage_root: Path, names: DocumentNames = DEFAULT_DOCUMENT_NAMES, *,
                 max_attempts: int = MAX_ATTEMPTS, retry_delay_s: float = RETRY_DELAY_S,
                 lease_s: float = LEASE_S, embedder: Embedder | None = None) -> str | None:
    """Take one due job and process it. Returns None when no job is due, else what happened: 'ready', 'failed',
    'retry', or 'taken over' when another worker took the job meanwhile. Needs a connection in autocommit mode,
    logged in as the documents role."""
    job = take_job(conn, schema, names, lease_s)
    if job is None:
        return None
    return run_job(conn, schema, storage_root, job, names, max_attempts=max_attempts, retry_delay_s=retry_delay_s,
                   embedder=embedder)


def take_job(conn, schema: str, names: DocumentNames = DEFAULT_DOCUMENT_NAMES, lease_s: float = LEASE_S) -> Job | None:
    jobs, versions = sql.Identifier(names.schema, "jobs"), sql.Identifier(schema, "document_versions")
    with conn.transaction():
        taken = conn.execute(sql.SQL(
            "UPDATE {jobs} SET status = 'running', attempts = attempts + 1, updated_at = now(), "
            "locked_until = now() + make_interval(secs => %s) "
            "WHERE id = (SELECT id FROM {jobs} WHERE (status = 'queued' AND run_after <= now()) "
            "OR (status = 'running' AND locked_until < now()) ORDER BY run_after, id LIMIT 1 FOR UPDATE SKIP LOCKED) "
            "RETURNING id, document_version_id, attempts").format(jobs=jobs), [lease_s]).fetchone()
        if taken is None:
            return None
        job_id, version_id, attempt = taken
        storage_key, media_type = conn.execute(sql.SQL(
            "UPDATE {} SET status = 'processing', error = NULL WHERE id = %s RETURNING storage_key, media_type"
        ).format(versions), [version_id]).fetchone()
    return Job(job_id, version_id, attempt, storage_key, media_type)


def run_job(conn, schema: str, storage_root: Path, job: Job, names: DocumentNames = DEFAULT_DOCUMENT_NAMES, *,
            max_attempts: int = MAX_ATTEMPTS, retry_delay_s: float = RETRY_DELAY_S,
            embedder: Embedder | None = None) -> str:
    """Read the job's file into passages and, when an embedder is given, their embeddings: all in one transaction, so
    a version is ready with all of them or with none."""
    jobs, versions = sql.Identifier(names.schema, "jobs"), sql.Identifier(schema, "document_versions")

    def hold() -> None:
        """Lock the job for the rest of the transaction, and make sure it is still this worker's. While it is
        locked, no other worker can take it, even if the lease runs out."""
        if conn.execute(sql.SQL("SELECT 1 FROM {} WHERE id = %s AND status = 'running' AND attempts = %s "
                                "FOR UPDATE").format(jobs), [job.id, job.attempt]).fetchone() is None:
            raise _NotOurs

    def finish(version_status: str, version_error: str | None, job_status: str, job_error: str | None,
               delay_s: float = 0.0) -> None:
        with conn.transaction():
            hold()
            conn.execute(sql.SQL("UPDATE {} SET status = %s, error = %s WHERE id = %s").format(versions),
                         [version_status, version_error, job.version_id])
            conn.execute(sql.SQL(
                "UPDATE {} SET status = %s, last_error = %s, locked_until = NULL, updated_at = now(), "
                "run_after = now() + make_interval(secs => %s) WHERE id = %s"
            ).format(jobs), [job_status, job_error, delay_s, job.id])

    try:
        try:
            with conn.transaction():
                hold()
                count = 0
                passages = chunks(read_blocks(stored_path(storage_root, job.storage_key), job.media_type))
                while batch := list(islice(passages, BATCH_INPUTS)):
                    vectors = embedder.embed([embedding_input(chunk.section, chunk.content)
                                              for chunk in batch]) if embedder else []
                    first = count + 1
                    with conn.cursor().copy(sql.SQL(
                            "COPY {} (document_version_id, chunk_no, page_number, section, content) FROM STDIN"
                    ).format(sql.Identifier(schema, "document_chunks"))) as copy:
                        for chunk in batch:
                            count += 1
                            copy.write_row((job.version_id, count, chunk.page, chunk.section, chunk.content))
                    if vectors:
                        with conn.cursor().copy(sql.SQL(
                                "COPY {} (document_version_id, chunk_no, model, embedding) FROM STDIN"
                        ).format(sql.Identifier(schema, "document_chunk_embeddings"))) as copy:
                            for offset, vector in enumerate(vectors):
                                copy.write_row((job.version_id, first + offset, embedder.model, vector_text(vector)))
                if not count:
                    raise ReadError("The file holds no text.")
                conn.execute(sql.SQL("UPDATE {} SET status = 'ready', error = NULL WHERE id = %s").format(versions),
                             [job.version_id])
                conn.execute(sql.SQL("UPDATE {} SET status = 'done', last_error = NULL, locked_until = NULL, "
                                     "updated_at = now() WHERE id = %s").format(jobs), [job.id])
            return "ready"
        except ReadError as error:
            finish("failed", str(error), "failed", str(error))
            return "failed"
        except _NotOurs:
            raise
        except Exception as error:  # a fault of the environment, not of the file: try again later
            # The detail goes to the server's log and the job table, which the agent cannot read. People and the
            # model see only the fixed message below.
            detail = f"{type(error).__name__}: {error}"
            print(f"document job {job.id} failed (attempt {job.attempt}): {detail}", file=sys.stderr)
            traceback.print_exc(file=sys.stderr)
            if job.attempt >= max_attempts:
                finish("failed", f"Processing failed after {job.attempt} attempts.", "failed", detail)
                return "failed"
            finish("pending", None, "queued", detail, retry_delay_s * 2 ** (job.attempt - 1))
            return "retry"
    except _NotOurs:
        print(f"document job {job.id}: another worker took it over; attempt {job.attempt} wrote nothing",
              file=sys.stderr)
        return "taken over"
